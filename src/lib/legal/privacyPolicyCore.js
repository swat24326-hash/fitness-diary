/**
 * Контакт для вопросов к обработчику. Пусто — на странице только «через клуб».
 * Задаётся `VITE_PRIVACY_CONTACT` (email), без хардкода в коде.
 */
export function privacyPolicyContact() {
  try {
    const raw = String(import.meta.env?.VITE_PRIVACY_CONTACT ?? '').trim()
    return raw.includes('@') ? raw : ''
  } catch {
    return ''
  }
}

