/**
 * Короткие пояснения к блокам статистики клуба (человеческим языком).
 * @typedef {'hall'|'completed'|'pnk'|'byDay'|'byTypes'|'clubMonthly'|'rating'|'coachQuality'|'clientRetention'|'clientAttendance'} AdminClubStatsHelpKey
 */

/**
 * @param {AdminClubStatsHelpKey} key
 * @param {{
 *   isTrainerScope?: boolean,
 *   showPzOnlyCards?: boolean,
 *   hallLabel?: string,
 *   windowDays?: number,
 *   asOf?: string,
 *   windowFrom?: string,
 * }} [ctx]
 * @returns {string[]}
 */
export function adminClubStatsHelpLines(key, ctx = {}) {
  const trainer = Boolean(ctx.isTrainerScope)
  const hall = String(ctx.hallLabel || '').trim()
  const windowDays = Number(ctx.windowDays) > 0 ? Number(ctx.windowDays) : 30
  const asOf = String(ctx.asOf || '').trim() || 'сегодня'
  const windowFrom = String(ctx.windowFrom || '').trim()

  switch (key) {
    case 'hall':
      return [
        'ПЗ, ТЗ и АЗ — разные залы. Цифры на экране только по выбранной вкладке.',
        'Одного человека не складывайте по трём вкладкам: он может быть сразу в нескольких залах.',
      ]
    case 'completed':
      return [
        'Список завершённых тренировок за выбранный период — те же, что в цифре «Проведено».',
        'БЗ (учёт в ПНК) и личные тренировки без типа карты сюда не входят.',
        trainer
          ? 'Здесь только ваши клиенты с планшета персонального зала.'
          : 'Это журнал планшета ПЗ: кто потренировался и у какого тренера.',
      ]
    case 'pnk':
      return [
        'Сколько человек из ПНК оформили ДК за период.',
        'Дробь на карточке: оформили / все ПНК; процент рядом — та же конверсия.',
        'Открытый ПНК в дроби есть, в «Всего клиентов» клуба — нет, пока не оформили.',
      ]
    case 'byDay':
      return [
        'Сколько тренировок провели по дням: завершённые и черновики (это не блок «Ритм»).',
        'Пунктир — средняя; серая линия — тот же день прошлого месяца (утро: сразу видно просадку).',
        'Светлее — выходные (от точки до точки), золотая полоса — сегодня.',
      ]
    case 'byTypes':
      return [
        trainer || ctx.showPzOnlyCards
          ? 'Сколько завершённых тренировок по типам платных карт. БЗ (это ПНК) и личные «Без типа» сюда не входят.'
          : `Сколько абонементов ${hall || 'зала'} по типу карты. Это не тренировки с планшета.`,
        'Если включён прогноз ЗП — справа база и итого с надбавкой кабинета.',
      ]
    case 'clubMonthly':
      return [
        'Картина по календарным месяцам выбранного года (январь–декабрь).',
        'Пунктир — средняя по месяцам, где уже были тренировки.',
        'Период сводки выше на этот график не режет: всегда полный год.',
        'В столбики идут тренировки с типом карты; «Без типа» не считаем.',
      ]
    case 'rating':
      return [
        'Сравнение тренеров клуба за период: объём, ритм, удержание и качество ведения.',
        'Можно открыть ИСКРУ по тренеру прямо из карточки.',
      ]
    case 'coachQuality':
      return [
        trainer
          ? 'Ваш балл качества ведения: карточки клиентов, глубина дневника и хвосты в «Неактивных».'
          : 'Средний балл тренеров и таблица, где видно, кто в порядке, а кого разобрать.',
        'Правила расчёта открываются кнопкой «!» у заголовка.',
      ]
    case 'clientRetention':
      return trainer
        ? [
            'Зачем вам: остаются ли ваши клиенты с планшетом ходить, продлевают ли абон и как долго живут в зале. Это не ЗП и не «Качество ведения».',
            'Удержание M+3 — прижились ли люди через 3 месяца после первого абонемента (когорты, не «итог выбранного месяца»).',
            'Продления 14 дн. — горячий срез: кто продлил в ближайшие 14 дней после конца абона.',
            'Продления за период — у кого абон кончился в выбранном периоде и кто купил следующий (тоже в окне 14 дней).',
            'Медиана жизни — типичный срок от первого ДК до архива или до сегодня.',
            'Архив / закрытия ПЗ — кто ушёл именно в выбранном периоде, не весь список вкладки «Архив».',
            'Если M+3 показывает «—» или «Рано» — клиенты только начали, рано сравнивать с коллегами.',
          ]
        : [
            'Зачем клубу: удерживаем ли клиентов ПЗ с планшетом — кто остался ходить, кто продлил и почему ушёл в архив. Отдельно от «Качества ведения» и чипа «Не активные».',
            'M+3 и медиана жизни — длинные метрики (когорты / срок жизни); фильтр месяца их почти не меняет.',
            'Удержание M+3 — доля людей с хотя бы одним ДК в 3‑м месяце после первого абонемента (только «созревшие» когорты). Не «удержание за сентябрь».',
            'Продления 14 дн. — короткий горячий срез; продления за период — итог по окончаниям абона в выбранном диапазоне.',
            'Архив за период — сколько убрали в выбранном периоде; «база» — все клиенты ПЗ с планшетом, не вкладка «Архив».',
            'Причины архива — из модалки «В архив», чтобы понимать отток.',
            'Возвраты — вернули из архива и снова ходили в течение 30 дней.',
            '«Рано» у тренера — с старта прошло меньше ~3 месяцев, M+3 ещё рано считать.',
          ]
    case 'clientAttendance': {
      const windowBit = windowFrom ? ` · окно ${windowFrom}…${asOf}` : ''
      return trainer
        ? [
            'Зачем вам: сколько в среднем ходят ваши клиенты с активным абоном (планшет) и где проседает ритм — до ухода в архив. Это не «проведено тренировок» за месяц сводки.',
            `Средняя посещаемость — ритм за последние ${windowDays} дней до ${asOf} (не за выбранный месяц в фильтре). Рядом — сравнение с предыдущими ${windowDays} днями.`,
            'Без выпадения — доля пула без паузы ≥14 дней с последнего визита.',
            'Структура ритма — для сравнения привычек, не список ФИО.',
          ]
        : [
            'Зачем клубу: сколько в среднем ходят клиенты с активным абоном (планшет) и где проседает ритм — до того, как человек уйдёт в архив. Это не «проведено тренировок» за месяц сводки.',
            `Средняя посещаемость — ритм за последние ${windowDays} дней до ${asOf} (не за месяц в фильтре). Рядом — сравнение с предыдущими ${windowDays} днями. Формула: (сумма завершённых ÷ пул) × (7 ÷ ${windowDays} дн.)${windowBit}.`,
            'Без выпадения — доля пула без паузы ≥14 дней с последнего визита.',
            'Структура ритма и таблица по тренерам — для сравнения, не список ФИО.',
          ]
    }
    default:
      return []
  }
}
