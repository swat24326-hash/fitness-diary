/**
 * Узор фона переписки (как обои Telegram, но про фитнес): public/chat/pattern-fitness.svg.
 * Контуры — иконки Lucide (ISC) из node_modules. Плитка бесшовная: значок у края дорисован с другой стороны.
 * node scripts/generate-chat-pattern.mjs
 */
import fs from 'node:fs/promises'
import path from 'node:path'

const TILE = 420
const OUT = path.resolve('public', 'chat', 'pattern-fitness.svg')

const BIG = [
  'dumbbell', 'apple', 'heart-pulse', 'timer', 'footprints', 'bike', 'trophy', 'flame', 'droplet', 'zap', 'medal',
  'biceps-flexed', 'banana', 'salad', 'carrot', 'activity', 'weight', 'target', 'volleyball', 'dribbble', 'shirt',
  'cherry', 'citrus', 'egg', 'fish', 'glass-water', 'milk', 'heart', 'sun', 'mountain', 'person-standing',
  'alarm-clock', 'calendar-check', 'smile', 'leaf', 'sprout', 'battery-charging', 'headphones', 'thumbs-up',
  'rocket', 'crown', 'goal', 'grape', 'watch', 'gauge', 'flag', 'music', 'moon', 'waves',
]
const SMALL = ['star', 'sparkles', 'heart', 'zap', 'droplet', 'leaf']

async function iconNode(name) {
  const src = await fs.readFile(path.resolve('node_modules/lucide-react/dist/esm/icons', `${name}.js`), 'utf8')
  const m = src.match(/createLucideIcon\("[^"]+", (\[[\s\S]*\])\);/)
  if (!m) throw new Error(`Не разобрал иконку ${name}`)
  return new Function(`return ${m[1]}`)()
}

function toSvg(node) {
  return node
    .map(([tag, attrs]) => {
      const a = Object.entries(attrs)
        .filter(([k]) => k !== 'key')
        .map(([k, v]) => `${k}="${v}"`)
        .join(' ')
      return `<${tag} ${a}/>`
    })
    .join('')
}

/** Повторяемый случайный ряд — узор не меняется от запуска к запуску. */
function rng(seed) {
  let s = seed >>> 0
  return () => {
    s = (s * 1664525 + 1013904223) >>> 0
    return s / 2 ** 32
  }
}

const rand = rng(20261015)
const placed = []

function torusDist(a, b) {
  const dx = Math.min(Math.abs(a.x - b.x), TILE - Math.abs(a.x - b.x))
  const dy = Math.min(Math.abs(a.y - b.y), TILE - Math.abs(a.y - b.y))
  return Math.hypot(dx, dy)
}

function scatter(names, { min, max, gap, tries, limit = Infinity, from = 0 }) {
  let i = from
  for (let fails = 0; fails < tries && i - from < limit; ) {
    const size = min + rand() * (max - min)
    /* Контур иконки не доходит до краёв своих 24×24 — круг чуть меньше половины, иначе на глаз пусто. */
    const p = { x: rand() * TILE, y: rand() * TILE, r: size * 0.43 }
    if (placed.some((q) => torusDist(p, q) < p.r + q.r + gap)) {
      fails += 1
      continue
    }
    placed.push({ ...p, size, name: names[i % names.length], rot: Math.round((rand() - 0.5) * 50) })
    i += 1
  }
}

/* Размеры плавно, от крупных к мелким, как у Telegram: каждый следующий заполняет щели, пустот и «песка» нет. */
const LEVELS = [
  [54, 6], [48, 7], [42, 9], [37, 11], [33, 13], [29, 16], [26, Infinity], [23, Infinity], [20, Infinity],
]
let next = 0
for (const [size, limit] of LEVELS) {
  const before = placed.length
  scatter(BIG, { min: size - 2, max: size + 2, gap: 4, tries: 3000, limit, from: next })
  next += placed.length - before
}
scatter(SMALL, { min: 12, max: 15, gap: 5, tries: 1500, limit: 24 })

const nodes = {}
for (const name of new Set(placed.map((p) => p.name))) nodes[name] = toSvg(await iconNode(name))

const STROKE_PX = 1.5
const groups = []
for (const p of placed) {
  const scale = p.size / 24
  const sw = (STROKE_PX / scale).toFixed(2)
  for (const ox of [-TILE, 0, TILE]) {
    for (const oy of [-TILE, 0, TILE]) {
      const x = p.x + ox
      const y = p.y + oy
      if (x + p.r < 0 || x - p.r > TILE || y + p.r < 0 || y - p.r > TILE) continue
      groups.push(
        `<g transform="translate(${x.toFixed(1)} ${y.toFixed(1)}) rotate(${p.rot}) scale(${scale.toFixed(3)}) translate(-12 -12)" stroke-width="${sw}">${nodes[p.name]}</g>`,
      )
    }
  }
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${TILE}" height="${TILE}" viewBox="0 0 ${TILE} ${TILE}">
<!-- Chat feed wallpaper (fitness doodles). Generated by scripts/generate-chat-pattern.mjs. Icon outlines: Lucide, ISC license. -->
<g fill="none" stroke="#fff" stroke-opacity=".1" stroke-linecap="round" stroke-linejoin="round">
${groups.join('\n')}
</g>
</svg>
`
await fs.writeFile(OUT, svg, 'utf8')
console.log(`Узор: ${placed.length} значков (${new Set(placed.map((p) => p.name)).size} видов), ${(svg.length / 1024).toFixed(1)} КБ → ${OUT}`)
