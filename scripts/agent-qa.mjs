function run(label, cmd, args, opts = {}) {
  console.log(`\n▶ ${label}`)
  const r = spawnSync(cmd, args, { stdio: 'inherit', shell: true, ...opts })
  if (r.status !== 0) {
    console.error(`✗ ${label}`)
    failed++
  } else {
    console.log(`✓ ${label}`)
  }
}

function check(cond, label) {
  if (cond) {
    console.log(`✓ ${label}`)
  } else {
    console.error(`✗ ${label}`)
    failed++
  }
}

